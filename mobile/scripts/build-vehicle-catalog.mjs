import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';

export const upstreamCommit='f37e44e01fad7f67d3625c95b792f2caa1524536';
export const upstreamSha256='405b677d96ee5f33bdc1e314ab74bcf5e7f5d112f176de335f1e9bafb5cff3a5';
export const upstreamUrl=`https://raw.githubusercontent.com/MeterApp/vehicle-db/${upstreamCommit}/data/compact.json`;
const allowedSources=['nhtsa-vpic','uk-dft-vehicle-licensing','eea-co2-monitoring','rdw-nl-vehicle-register'];
const key=value=>value.normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/ł/g,'l').replace(/Ł/g,'L').toLowerCase().trim().replace(/\s+/g,' ');
const compare=(a,b)=>key(a)<key(b)?-1:key(a)>key(b)?1:0;
function name(value,max){
 if(typeof value!=='string'||/[\u0000-\u001f\u007f]/.test(value))throw new Error('Invalid catalog name');
 const clean=value.trim().replace(/\s+/g,' ');
 if(!clean||clean.length>max)throw new Error(`Catalog name exceeds garage limits: ${clean.slice(0,100)}`);
 return clean;
}
export function extractCatalog(data){
 if(!data||!['sources','makes','modelNames','models'].every(k=>Array.isArray(data[k]))||data.sources.length<1||data.sources.length>30)throw new Error('Unsupported catalog schema');
 const sourceIds=data.sources.map(s=>s.source_id);
 if(sourceIds.some(id=>typeof id!=='string')||new Set(sourceIds).size!==sourceIds.length)throw new Error('Invalid catalog sources');
 const allowedMask=sourceIds.reduce((mask,id,i)=>allowedSources.includes(id)?mask+2**i:mask,0);
 if(!allowedMask)throw new Error('No reviewed catalog source');
 const makes=new Map();
 for(const make of data.makes){if(!Number.isSafeInteger(make.make_id)||makes.has(make.make_id))throw new Error('Invalid catalog make');makes.set(make.make_id,make.make_name);}
 const groups=new Map();
 for(const row of data.models){
  if(!Array.isArray(row)||row.length!==6||!row.every(Number.isSafeInteger)||row[0]<1900||row[0]>9999||row[3]<0||row[3]>=data.modelNames.length||row[4]<1||row[5]<1||row[5]>=2**sourceIds.length||!makes.has(row[1]))throw new Error('Invalid catalog model tuple');
  if(![2,7].includes(row[4])||!(row[5]&allowedMask))continue;
  const makeName=name(makes.get(row[1]),60),modelName=name(data.modelNames[row[3]],80),makeKey=key(makeName);
  if(!groups.has(makeKey))groups.set(makeKey,{name:makeName,models:new Map()});
  const models=groups.get(makeKey).models;
  if(!models.has(key(modelName)))models.set(key(modelName),modelName);
 }
 if(!groups.size)throw new Error('Catalog contains no usable passenger cars');
 return [...groups.values()].map(g=>({name:g.name,models:[...g.models.values()].sort(compare)})).sort((a,b)=>compare(a.name,b.name));
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const input=process.argv.indexOf('--input');
 let bytes;
 if(input!==-1){if(!process.argv[input+1])throw new Error('--input requires a file');bytes=await readFile(process.argv[input+1]);}
 else{const response=await fetch(upstreamUrl,{signal:AbortSignal.timeout(30000)});if(!response.ok)throw new Error(`Catalog download HTTP ${response.status}`);bytes=Buffer.from(await response.arrayBuffer());}
 if(createHash('sha256').update(bytes).digest('hex')!==upstreamSha256)throw new Error('Catalog SHA-256 mismatch; review a new snapshot before updating');
 const source=JSON.parse(bytes.toString('utf8'));
 const makes=extractCatalog(source);
 const metadata={upstreamCommit,upstreamSha256,snapshotDate:'2026-11-25',sources:source.sources.filter(s=>allowedSources.includes(s.source_id))};
 const content=`// Generated by scripts/build-vehicle-catalog.mjs; see assets/catalog/README.md.\nexport type CatalogMake={name:string;models:string[]};\nconst makes:CatalogMake[]=${JSON.stringify(makes)};\nexport const catalogProvenance=${JSON.stringify(metadata)} as const;\nexport default makes;\n`;
 const target=new URL('../src/vehicle-catalog-data.ts',import.meta.url);
 const metadataTarget=new URL('../assets/catalog/provenance.json',import.meta.url);
 const provenance=JSON.stringify(metadata,null,2)+'\n';
 if(process.argv.includes('--check')){
  if(await readFile(target,'utf8')!==content||await readFile(metadataTarget,'utf8')!==provenance)throw new Error('Bundled catalog is not reproducible');
 }else{
  await mkdir(new URL('../assets/catalog/',import.meta.url),{recursive:true});
  await writeFile(target,content);await writeFile(metadataTarget,provenance);
 }
 console.log(JSON.stringify({makes:makes.length,models:makes.reduce((n,m)=>n+m.models.length,0),bundledBytes:Buffer.byteLength(content),checked:process.argv.includes('--check')}));
}
